#define DISTRO_ARTS_COUNT \
    (sizeof(DISTRO_ARTS) / sizeof(DISTRO_ARTS[0]))

static inline const DistroArt *distro_art_find(const char *name)
{
    const DistroArt *fallback = NULL;
    for (size_t i = 0; i < DISTRO_ARTS_COUNT; i++) {
        if (strcmp(DISTRO_ARTS[i].name, "unknown") == 0)
            fallback = &DISTRO_ARTS[i];
        if (name && strcmp(DISTRO_ARTS[i].name, name) == 0)
            return &DISTRO_ARTS[i];
    }
    return fallback;
}

