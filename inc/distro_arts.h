typedef struct {
    const char *name;
    const char *color;
    const char *lines[DISTRO_LINES];
} DistroArt;


static inline void distro_art_print(const DistroArt *art)
{
    if (!art) return;
    for (int i = 0; i < DISTRO_LINES; i++)
        printf("%s%s" R "\n", art->color, art->lines[i]);
}

